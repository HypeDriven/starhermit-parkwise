function solution(level) {
  let s = R.makeState(level);
  const moves = [];
  while (!R.isWin(s)) {
    const sol = R.solve(s);
    if (!sol || !sol.firstMove) throw new Error('unsolvable');
    moves.push({ ...sol.firstMove, before: s });
    s = R.applyMove(s, sol.firstMove.v, sol.firstMove.dir, sol.firstMove.dist);
  }
  return moves;
}
const vehicleName = (v) => v.target ? 'red car' : `${v.ori === 'h' ? 'sideways' : 'upright'} ${v.len === 3 ? 'van' : 'car'} ${v.id}`;
const label = (v) => `${vehicleName(v)} at column ${v.x + 1}, row ${v.y + 1}${v.target ? ' (target)' : ''}`;

/** Key lines solving a lot from its start (the red car selected). */
function byKeys(level) {
  const out = [];
  let sel = R.targetVehicle(R.makeState(level));
  for (const m of solution(level)) {
    const n = m.before.vehicles.length;
    for (let k = (m.v - sel + n) % n; k > 0; k--) out.push('key KeyN 1', 'frames 2');
    sel = m.v;
    const v = m.before.vehicles[m.v];
    const key = v.ori === 'h' ? (m.dir > 0 ? 'ArrowRight' : 'ArrowLeft') : (m.dir > 0 ? 'ArrowDown' : 'ArrowUp');
    for (let d = 0; d < m.dist; d++) out.push(`key ${key} 1`, 'frames 3');
  }
  return out;
}
/** Presses on the vehicle's and the marker's named targets (`press` is click or touch). */
function byTargets(level, press) {
  const out = [];
  for (const m of solution(level)) {
    const v = m.before.vehicles[m.v];
    const nx = v.ori === 'h' ? v.x + m.dir * m.dist : v.x, ny = v.ori === 'v' ? v.y + m.dir * m.dist : v.y;
    out.push(`${press} =${label(v)}`, 'frames 8', `${press} =Slide the ${vehicleName(v)} to column ${nx + 1}, row ${ny + 1}`, 'frames 12');
  }
  return out;
}
const head = (text, viewport) => [`# ${text}`, `# viewport ${viewport}`, `# Generated by tools/gen-plays.mjs from the rules' solver.`];

export function dailyPlay(day) {
  const e = C.dailyLevel(day);
  return [...head(`The Daily of ${day} solved by keys (par ${e.par}).`, '1280x800@1'),
    'until 600 Daily challenge', 'frames 20', 'click =Daily challenge', 'until 600 Moves 0 / par', 'frames 30',
    ...byKeys(e.level), 'until 300 Lot cleared!', 'frames 10', 'expect Daily', 'save daily-done'].join('\n') + '\n';
}

