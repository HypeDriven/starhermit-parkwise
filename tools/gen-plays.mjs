// solver: every round is played with the moves rules.js solve() finds,
// entered as the player would — by keys (N picks the next vehicle, the
// arrows slide it one cell a press) or by pressing the vehicle's and the
// legal-target marker's named targets (a click on the desktop, a finger on
// the phones). `dailyPlay(day)` makes the Daily's script for a date
// (tests/native.mjs plays today's).
//   node tools/gen-plays.mjs
